    private static readonly Lazy<bool> HeicLazy = new(() => CanDecode(HeicSample));
    private static readonly Lazy<bool> AvifLazy = new(() => CanDecode(AvifSample));

    public static bool Heic => HeicLazy.Value;

    public static bool Avif => AvifLazy.Value;

    private static bool CanDecode(ReadOnlySpan<byte> sample)
    {
        try
        {
            var decoder = BitmapDecoder.Create(new MemoryStream(sample.ToArray()), BitmapCreateOptions.None,
                BitmapCacheOption.OnLoad);
            return decoder.Frames[0].PixelWidth > 0;
        }
        catch (Exception)
        {
            return false;
        }
    }

